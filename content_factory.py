"""تحويل نتائج التحليل المحفوظة إلى تكليف إنتاج محتوى متعدد المنصات."""
from __future__ import annotations
from datetime import datetime, timezone
import hashlib
import json

import prompt_style

OUTPUTS = {
    "حزمة كاملة": ["سكريبت رئيسي", "ريلز/شورتس", "خريطة مشاهد ولقطات بالتوقيت", "قائمة B-roll والمواد البصرية", "برومبتات توليد الصور والمشاهد", "3 أفكار للصورة المصغرة", "عناوين وخطافات", "وصف ومنشور", "قائمة المصادر والتحقق"],
    "فيديو طويل": ["سكريبت رئيسي", "خريطة مشاهد ولقطات بالتوقيت", "قائمة B-roll والمواد البصرية", "برومبتات توليد الصور والمشاهد", "3 أفكار للصورة المصغرة", "عناوين وخطافات", "وصف الفيديو", "فصول الفيديو", "قائمة المصادر والتحقق"],
    "ريلز وشورتس": ["3 سكريبتات قصيرة مختلفة الزاوية", "Storyboard رأسي 9:16 لكل نسخة", "لقطات B-roll وانتقالات سريعة", "برومبتات صور ومشاهد رأسية", "نصوص الشاشة والكابشن", "خطافات بديلة", "قائمة المصادر والتحقق"],
    "منشورات وعناوين": ["10 عناوين", "3 منشورات", "3 تصورات صور مصغرة", "برومبتات صور المنشورات", "وصف مختصر", "أسئلة تفاعل", "قائمة المصادر والتحقق"],
    "خطة بصرية فقط": ["Storyboard كامل بالمشاهد والتوقيت", "قائمة لقطات B-roll", "برومبت مستقل لكل صورة أو مشهد", "تصميم الصورة المصغرة بثلاثة اتجاهات", "نصوص الشاشة والجرافيك", "خطة المونتاج والصوت", "قائمة التحقق البصري والمصدري"],
    "خريطة مونتاج تنفيذية": ["تقسيم السكريبت إلى وحدات إلقاء مرقمة", "ربط كل وحدة إلقاء بمشهد ولقطة محددين", "جدول مونتاج زمني متعدد المسارات", "قائمة الأصول المطلوبة وحالة كل أصل", "خطة التعليق الصوتي والموسيقى والمؤثرات", "ملف EDL نصي قابل للتحويل إلى CSV", "قائمة مراجعة قبل التصدير"],
}


def build_content_prompt(case_title, analysis_text, output_type="حزمة كاملة", audience="الجمهور العام",
                         dialect="عامية مصرية مبسطة", duration="3 إلى 5 دقائق", platform="فيسبوك ويوتيوب وتيك توك"):
    """يبني برومبت إنتاج من نتيجة تحليل موجودة، دون إضافة حقائق من خارجها."""
    if output_type not in OUTPUTS:
        raise ValueError("نوع مخرج المحتوى غير معروف")
    if not str(analysis_text or "").strip():
        raise ValueError("لا توجد نتيجة تحليل يمكن البناء عليها")
    if len(analysis_text) > 150_000:
        raise ValueError("نتيجة التحليل طويلة جداً؛ قسّمها إلى أجزاء قبل تجهيز تكليف الإنتاج")
    deliverables = "\n".join(f"{i}. {name}" for i, name in enumerate(OUTPUTS[output_type], 1))
    return f'''أنت غرفة تحرير وإنتاج محتوى. مهمتك تحويل التحليل المرفق إلى مواد نشر دقيقة وجذابة.

## بيانات التكليف
القضية: {case_title or 'قضية غير معنونة'}
نوع الحزمة: {output_type}
الجمهور: {audience}
المنصة: {platform}
اللهجة: {dialect}
المدة المستهدفة للفيديو الرئيسي: {duration}

## المخرجات المطلوبة
{deliverables}

## تعليمات خاصة بنوع المخرج
{("إذا كان نوع المخرج «خريطة مونتاج تنفيذية»، فلا تكتب سكريبتاً جديداً من الصفر. استخرج وحدات الإلقاء من النص المتاح في التحليل أو من السكريبت إن كان مرفقاً، وعلّم أي نص غير متاح بأنه [يحتاج سكريبت]. اجعل جدول الربط وAsset Manifest وEDL/TSV هي المخرجات الأساسية." if output_type == "خريطة مونتاج تنفيذية" else "نفّذ جميع المخرجات المحددة أعلاه، وأدرج خريطة الربط وAsset Manifest وEDL/TSV كلما احتوى المخرج على فيديو أو مشاهد.")}

## قواعد تحرير لا يجوز تجاوزها
- اعتبر التحليل المرفق المصدر الوحيد للوقائع في هذا التكليف. لا تضف معلومات خارجية أو أرقاماً أو تواريخ أو أسماء أو اقتباسات غير واردة فيه.
- افصل بوضوح بين الواقعة الموثقة، والادعاء المنسوب، والتحليل، والسيناريو المحتمل.
- لا تحول الاحتمال إلى حقيقة، ولا تنسب نوايا أو تنسيقاً أو مسؤولية بلا دليل.
- إذا كانت معلومة مهمة ناقصة أو متناقضة، ضع علامة [تحتاج تحقق] ولا تملأ الفراغ بالتخمين.
- لا تحذف التحفظات الضرورية لمجرد جعل النص أكثر إثارة.
- اجعل النص صالحاً للإلقاء: جمل قصيرة، انتقالات طبيعية، وتجنب لغة التقارير الجامدة.
- لا تستخدم خطافاً مضللاً أو عنواناً يوحي بما لا يثبته التحليل.
- افصل المصادر والملاحظات التحريرية عن نص الإلقاء.
- اختم كل مادة بقائمة قصيرة لما يجب مراجعته قبل النشر.

## مواصفات خاصة بالسكريبت
{prompt_style.CAIRO_STYLE if "مصري" in dialect or "مصرية" in dialect else ""}
اكتب باللهجة المطلوبة بصورة طبيعية، لا تترجم الفصحى كلمة بكلمة. {prompt_style.AR_NAMES_RULE} ابدأ بسؤال أو مفارقة أو معلومة محورية مثبتة، ثم اشرح ماذا حدث ولماذا يهم ومن المستفيد والمتضرر وما الذي لا نعرفه بعد. اجعل الخاتمة خلاصة مشروطة وسؤالاً يفتح النقاش دون تلقين الجمهور رأياً.

## دليل الإخراج البصري والتنفيذ
أنشئ خطة إنتاج قابلة للتنفيذ في المونتاج، لا تكتفِ باقتراحات عامة:
1. ابدأ بملخص الهوية البصرية: المزاج، الإضاءة، الألوان، الإيقاع، ونمط الجرافيك، مع الحفاظ على الاتساق بين المشاهد.
2. أنشئ جدول Storyboard بأعمدة: رقم المشهد، التوقيت التقريبي، الجزء المنطوق من السكريبت، ما يظهر على الشاشة، نوع اللقطة وحركة الكاميرا، نص الشاشة، المؤثر الصوتي/الموسيقى، ومصدر اللقطة أو طريقة إنتاجها.
3. لكل مشهد اكتب برومبتاً بصرياً مستقلاً قابلاً للنسخ إلى مولد صور/فيديو. صف التكوين، زاوية الكاميرا، العدسة أو المنظور، الإضاءة، الخلفية، الحركة، ونسبة الأبعاد المناسبة (16:9 للفيديو الطويل و9:16 للريلز ما لم تحدد المنصة غير ذلك).
4. افصل اللقطات الأرشيفية الحقيقية عن الصور التوضيحية المولدة. لا تصف صورة مولدة كأنها دليل فوتوغرافي أو لقطة حقيقية للحدث. ضع على إعادة التمثيل أو التصور عبارة واضحة مثل «تصور توضيحي» عند الحاجة.
5. لا تطلب من مولد الصور كتابة عناوين أو نصوص عربية داخل الصورة؛ اترك مساحة نظيفة لإضافة النص في المونتاج. اكتب النصوص المقترحة منفصلة.
6. اقترح ثلاث صور مصغرة مختلفة، ولكل واحدة: الفكرة، توزيع العناصر، تعبير/عنصر بصري غير مضلل، نص قصير جداً يضاف لاحقاً، وألوان مقترحة. لا تستخدم وجوهاً أو شعارات أو أعلاماً توحي بوجود أشخاص أو جهات لم يذكرها التحليل.
7. جهّز قائمة B-roll عملية: اللقطة المطلوبة، كلمات بحث عربية وإنجليزية، بديل مجاني/مولد، وسبب استخدامها. لا تخترع رابطاً أو تدّعِ ترخيصاً.
8. ضع خطة مونتاج تشمل الإيقاع، أماكن القطع، الانتقالات، الخرائط/الخطوط الزمنية/الإنفوجرافيك، ومستويات الصوت. تجنب المؤثرات التي توحي بالخطر أو الانفجار أو المواجهة إذا لم يسندها التحليل.
9. اربط كل مشهد بمعلومة أو فكرة من التحليل. إذا لم توجد مادة بصرية تثبت الواقعة، استخدم رسماً توضيحياً أو خريطة معنونة بوضوح، لا مشهداً تمثيلياً يوهم بأنه تسجيل حقيقي.

## خريطة الربط بين الكلام والصورة والمونتاج (إلزامية في كل مخرج مرئي)
أنشئ خريطة تنفيذية تمنع انفصال الصورة عن الكلام:
1. قسّم نص الإلقاء إلى وحدات قصيرة مرقمة بصيغة U001, U002... وانقل نص كل وحدة حرفياً دون إعادة صياغة داخل جدول الربط.
2. اربط كل وحدة إلقاء بمعرّف مشهد SH001, SH002... ولقطة SHOT001, SHOT002... ولا تترك أي وحدة بلا لقطة أو سبب تحريري واضح لترك الشاشة على المتحدث.
3. حافظ على ترتيب الكلام كما سيُسجل. لا تضع لقطة قبل المعلومة التي تشرحها إذا كان ذلك سيكشف استنتاجاً قبل سياقه.
4. أنشئ جدولاً بأعمدة: In/Out تقديري، معرف الوحدة، النص المنطوق حرفياً، معرف المشهد/اللقطة، وصف الصورة، نوع الأصل (أرشيف موثق/تصوير جديد/خريطة أو جرافيك/توليد توضيحي/ظهور المقدم)، النص على الشاشة، حركة الكاميرا، الانتقال، الصوت، وملاحظة التحقق.
5. أنشئ قائمة أصول Asset Manifest بمعرف فريد لكل ملف مطلوب، واسم ملف مقترح لاتيني بسيط، والوصف، والمصدر المطلوب أو كلمات البحث، والحالة (موجود/يحتاج تنزيل/يحتاج تصوير/يحتاج توليد/يحتاج تحقق). لا تخترع أن ملفاً موجود بالفعل.
6. أنشئ جدول EDL نصياً مفصولاً بعلامة tab (TSV) بأعمدة: track, start, end, asset_id, shot_id, action, audio_note. استخدم توقيتاً نسبياً يبدأ من 00:00، واجعل المسارات V1 للفيديو الأساسي وV2 للجرافيك وA1 للتعليق وA2 للموسيقى وA3 للمؤثرات. اكتب التوقيتات تقديرية ووضح أنها تحتاج ضبطاً بعد التسجيل.
7. قدم ترتيب تنفيذ عملي: تسجيل التعليق أولاً، ثم اختيار/إنشاء الأصول، ثم تركيب الصورة، ثم النصوص والجرافيك، ثم الصوت، ثم مراجعة المطابقة والتصدير.
8. لا تدّعِ إنشاء ملف مشروع CapCut أو Filmora أو Premiere قابل للفتح ما لم تكن قد أنشأت ملفاً حقيقياً بصيغته. قدم جدول EDL/TSV كخطة نقل يدوية قابلة للاستيراد أو التحويل حسب البرنامج، واذكر القيود.
9. لكل أصل مولد، قدم برومبتاً منفصلاً مع negative prompt عند الحاجة، واحتفظ بثبات الشخصيات والمواقع والملابس والعناصر بين اللقطات المتصلة. لا تضع نصوصاً داخل الصورة.
10. أضف نسخة بديلة منخفضة التكلفة تعتمد على خرائط ورسوم ونصوص وصور مرخصة بدلاً من توليد فيديو لكل مشهد.

## التحليل المعتمد
{analysis_text}

## فحص ما قبل التسليم
في نهاية المخرجات أضف جدول تدقيق: العبارة أو المعلومة | موضعها في التحليل | نوعها (واقعة/ادعاء/استنتاج/سيناريو) | هل تحتاج تحققاً؟
'''


def create_job(case_id, case_title, result_id, analysis_text, output_type="حزمة كاملة", audience="الجمهور العام",
               dialect="عامية مصرية مبسطة", duration="3 إلى 5 دقائق", platform="فيسبوك ويوتيوب وتيك توك"):
    prompt = build_content_prompt(case_title, analysis_text, output_type, audience, dialect, duration, platform)
    digest = hashlib.sha256(prompt.encode("utf-8")).hexdigest()
    return {"id": f"content_{int(datetime.now(timezone.utc).timestamp() * 1000000)}", "case_id": case_id,
            "case_title": case_title, "result_id": result_id, "created_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
            "output_type": output_type, "audience": audience, "dialect": dialect, "duration": duration,
            "platform": platform, "prompt": prompt, "sha256": digest}


def render_json(job):
    return json.dumps(job, ensure_ascii=False, indent=2)
