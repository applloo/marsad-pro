def split_words(line):
    return [w.strip() for w in re.split(r"[,،;\n]+", line or "") if w.strip()]


def merge_line(existing, add):
    """بيضم كلمات جديدة لسطر موجود من غير تكرار، بالفاصلة العربي"""
    out = split_words(existing)
    seen = {w.lower() for w in out}
    for w in split_words(add):
        if w.lower() not in seen:
            out.append(w)
            seen.add(w.lower())
    return "، ".join(out)


def clean(d):
    """بيتأكد إن شكل القاموس سليم (بعد التعديل في الجدول)، وبيشيل الصفوف الفاضية"""
    groups = []
    for g in (d or {}).get("groups") or []:
        if not isinstance(g, dict) or not str(g.get("name") or "").strip():
            continue
        rows = []
        for r in g.get("rows") or []:
            if not isinstance(r, dict):
                continue
            name, line = str(r.get("name") or "").strip(), str(r.get("line") or "").strip()
            if name and line:
                rows.append({"name": name, "note": str(r.get("note") or "").strip(), "line": merge_line("", line)})
        groups.append({"name": str(g["name"]).strip(), "rows": rows})
    return {"version": 1, "groups": groups}


def search(d, q):
    """بيرجع (اسم المجموعة، الصف) لكل صف فيه الكلمة في الاسم أو الملاحظة أو السطر"""
    q = (q or "").strip().lower()
    out = []
    for g in d.get("groups") or []:
        for r in g.get("rows") or []:
            if not q or q in (r["name"] + " " + r.get("note", "") + " " + r["line"]).lower():
                out.append((g["name"], r))
    return out
